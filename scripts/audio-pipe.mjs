/**
 * The audio pipeline (audio plan v1 §6, ADR-139) — `pnpm audio`, also inside `pnpm art`.
 *
 *   1. Renders every placeholder in src/data/audio/manifest.json from its source
 *      (synth recipe or song) into src/assets/audio/<file>.wav — mono, 8-bit,
 *      22.05 kHz (beds 11.025 kHz). Seeded per file: byte-identical renders.
 *   2. Writes src/assets/audio/LICENSES.md from the manifest; fails on any file
 *      whose licence is not CC0 / user-recording / original.
 *   3. Removes stale renders and reports the size against the 15 MB budget.
 *
 * Final files (your recordings, CC0 downloads) arrive in step 2 of the plan
 * once ffmpeg is installed: `tier: "final"` entries are never re-rendered.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderRecipe, renderSong, seedOf, wav8 } from './audio/synth.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const dataDir = resolve(here, '../src/data/audio');
const outDir = resolve(here, '../src/assets/audio');
const LICENCES = ['CC0', 'user-recording', 'original'];
const BUDGET_BYTES = 15 * 1024 * 1024;

export async function runAudioPipe({ quiet = false } = {}) {
  const { tokens } = JSON.parse(readFileSync(join(dataDir, 'manifest.json'), 'utf8'));
  const recipes = {};
  for (const f of readdirSync(join(dataDir, 'synth')).filter((x) => x.endsWith('.json'))) recipes[`synth/${f}`] = JSON.parse(readFileSync(join(dataDir, 'synth', f), 'utf8'));
  mkdirSync(outDir, { recursive: true });

  const problems = [];
  const wanted = new Set(Object.values(tokens).flatMap((e) => e.files.map((f) => `${f}.wav`)));
  // Stale renders (a token renamed or removed) go first — macOS filenames ignore case, so a rename to lower case must not delete its own new file.
  for (const f of readdirSync(outDir).filter((x) => x.endsWith('.wav'))) if (!wanted.has(f)) rmSync(join(outDir, f));
  let rendered = 0;
  for (const [token, e] of Object.entries(tokens)) {
    if (!LICENCES.includes(e.licence)) problems.push(`${token}: licence "${e.licence}" is not one of ${LICENCES.join(', ')}`);
    for (const file of e.files) {
      if (e.tier === 'final') continue;
      const sr = e.sampleRate ?? 22050;
      let samples;
      if (e.source.startsWith('songs/')) samples = renderSong(JSON.parse(readFileSync(join(dataDir, e.source), 'utf8')), sr, seedOf(file));
      else {
        const recipe = recipes[e.source]?.[file];
        if (!recipe) { problems.push(`${token}: no recipe "${file}" in ${e.source}`); continue; }
        samples = renderRecipe(recipe, sr, seedOf(file));
      }
      writeFileSync(join(outDir, `${file}.wav`), wav8(samples, sr));
      rendered++;
    }
  }

  const rows = Object.entries(tokens).filter(([, e]) => e.files.length).map(([t, e]) => `| \`${t}\` | ${e.files.map((f) => `\`${f}.wav\``).join(' ')} | ${e.licence} | ${e.tier} | ${e.source.startsWith('songs/') ? `original composition, \`src/data/audio/${e.source}\`` : e.licence === 'original' ? `generated by scripts/audio/synth.mjs from \`src/data/audio/${e.source}\`` : e.source} |`);
  writeFileSync(join(outDir, 'LICENSES.md'), `# Audio licences\n\nGenerated by \`scripts/audio-pipe.mjs\` from \`src/data/audio/manifest.json\` — do not edit by hand. Only CC0, the user's own recordings and original compositions are allowed (audio plan v1 §5, ADR-139); \`pnpm validate\` fails otherwise.\n\n| Token | Files | Licence | Tier | Source |\n|---|---|---|---|---|\n${rows.join('\n')}\n`);

  const bytes = readdirSync(outDir).filter((x) => /\.(wav|ogg|m4a)$/.test(x)).reduce((n, f) => n + statSync(join(outDir, f)).size, 0);
  if (bytes > BUDGET_BYTES) problems.push(`audio is ${(bytes / 1048576).toFixed(1)} MB — over the 15 MB budget`);
  if (!quiet) console.log(`✓ audio: ${rendered} placeholder${rendered === 1 ? '' : 's'} rendered, ${Object.keys(tokens).length} tokens, ${(bytes / 1048576).toFixed(2)} MB of 15 MB`);
  if (problems.length) {
    console.error(`\n✗ audio pipeline (${problems.length}):\n${problems.map((p) => `  • ${p}`).join('\n')}\n`);
    process.exitCode = 1;
  }
  return { rendered, bytes, problems };
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  if (!existsSync(dataDir)) { console.error('no src/data/audio'); process.exit(1); }
  await runAudioPipe();
}
