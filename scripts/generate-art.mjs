/**
 * Generates the pixel art: one street tileset and three character sheets.
 *
 * The art is code rather than opaque PNGs, which buys three things: it is
 * reproducible (same input, byte-identical output, so a rerun never dirties
 * the repo), it is editable (change the palette once, every tile follows), and
 * it cannot drift off-palette. Run it with:
 *
 *   corepack pnpm art
 */
import sharp from 'sharp';
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { Canvas } from './art/canvas.mjs';
import { T as TOK } from './art/palette.mjs';
import { T, TILES } from './art/tiles.mjs';
import { CH, CW, buildCharacterSheet } from './art/character.mjs';
import { importSheet } from './import-sheet.mjs';

// Tokens first: palette.gpl + tokens.mjs → tokens.json, which the runtime reads.
execFileSync(process.execPath, [join(dirname(fileURLToPath(import.meta.url)), 'generate-tokens.mjs')], { stdio: 'inherit' });

const here = dirname(fileURLToPath(import.meta.url));
const assets = resolve(here, '../src/assets');

const write = async (canvas, path) => {
  mkdirSync(dirname(path), { recursive: true });
  await sharp(canvas.data, {
    raw: { width: canvas.width, height: canvas.height, channels: 4 },
  })
    // Palette PNG: correct for low-colour art and much smaller than truecolour.
    .png({ palette: true, compressionLevel: 9, effort: 10, dither: 0 })
    .toFile(path);
};

// ── Tileset ────────────────────────────────────────────────────────────────
// 8 columns keeps the sheet compact and the ids easy to reason about in Tiled.
const COLS = 8;
const rows = Math.ceil(TILES.length / COLS);
const sheet = new Canvas(COLS * T, rows * T);

TILES.forEach(([, draw], i) => {
  const tile = new Canvas(T, T);
  draw(tile);
  sheet.blit(tile, (i % COLS) * T, Math.floor(i / COLS) * T);
});

await write(sheet, join(assets, 'tilesets/street.png'));

// ── Characters ─────────────────────────────────────────────────────────────
// One rig, many looks (P1_P2 §2.2): base body (gender) × skin tone × attire ×
// bag. The player gets every gender × skin × age combination so character
// creation can *assign* a sheet rather than customise one; `sheetForProfile`
// in src/utils/profile.ts must produce exactly these keys.
//
// Citizens reuse the rig with other attire — a visibly mixed crowd for no
// extra drawing. Every colour is a token on palette.gpl.
const LOOKS = {};
const tee = (c) => ({ top: TOK[`cloth.tee.${c}`], topShade: TOK[`cloth.tee.${c}.shade`] });
const kurti = (c) => ({ top: TOK[`cloth.kurti.${c}`], topShade: TOK[`cloth.kurti.${c}.shade`], bottom: TOK['cloth.legging'], bottomShade: TOK['cloth.legging'] });
Object.assign(LOOKS, {
  citizen:        { gender: 'M', skin: 3, bag: 'none', ...tee('olive') },
  citizen_teal:   { gender: 'F', skin: 2, bag: 'sling', ...kurti('green') },
  citizen_ochre:  { gender: 'M', skin: 4, bag: 'none', top: TOK['cloth.shirt.white'], topShade: TOK['cloth.shirt.white.shade'], hair: 'brown' },
  citizen_maroon: { gender: 'F', skin: 3, bag: 'none', ...kurti('red') },
  citizen_olive:  { gender: 'M', skin: 2, bag: 'laptop', ...tee('rust') },
  citizen_slate:  { gender: 'M', skin: 5, bag: 'backpack' },
  citizen_violet: { gender: 'F', skin: 1, bag: 'tote', ...kurti('mustard'), hair: 'brown' },
  citizen_sand:   { gender: 'F', skin: 5, bag: 'none', ...kurti('green') },
});

for (const [name, look] of Object.entries(LOOKS)) {
  await write(buildCharacterSheet(look), join(assets, `sprites/${name}.png`));
}

// ── Player sheets: imported, not drawn (AUDIT_LOG P2 round 1) ──────────────
// Each raw in _raw/characters/ is a generated 3×4 sheet in the reference
// style; import-sheet keys, snaps and quantises it into the 4×4 contract and
// writes the five skin tones. Regenerating from the raws is what keeps
// `pnpm art` reproducible for these too.
const rawDir = join(assets, '_raw/characters');
const imported = [];
for (const file of readdirSync(rawDir).filter((f) => f.endsWith('.png')).sort()) {
  imported.push(...(await importSheet(join(rawDir, file), file.replace(/\.png$/, ''), { skins: true })));
}

// ── Tile id manifest ───────────────────────────────────────────────────────
// Named ids so map generation and scene code never hard-code a bare number.
const ids = Object.fromEntries(TILES.map(([name], i) => [name, i]));
writeFileSync(
  join(assets, 'tilesets/street.tiles.json'),
  `${JSON.stringify(
    {
      $comment:
        'Generated by scripts/generate-art.mjs — tile name to 0-based index in street.png. Append-only: inserting a tile would renumber every map that uses it.',
      columns: COLS,
      tileSize: T,
      tileCount: TILES.length,
      ids,
    },
    null,
    2,
  )}\n`,
);

console.log(
  `✓ street.png — ${TILES.length} tiles (${COLS}x${rows} @ ${T}px = ${COLS * T}x${rows * T})`,
);
console.log(`✓ ${Object.keys(LOOKS).length} citizen sheets drawn + ${imported.length} player sheets imported (${CW}x${CH} frames, 4x4)`);
console.log(`✓ street.tiles.json — ${Object.keys(ids).length} named tile ids`);
